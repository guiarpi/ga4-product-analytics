"""powerbi_export.py — the SQL-only mode and the pre-computed tables, offline."""
import pandas as pd

import powerbi_export as pe
import queries


def test_sql_only_writes_every_extract_from_queries_py(tmp_path):
    paths = pe.write_sql(tmp_path)
    assert {p.stem for p in paths} == {name for name, _ in pe.EXTRACTS}
    sessions = (tmp_path / "fct_sessions.sql").read_text()
    assert "generated by powerbi_export.py from queries.pbi_sessions_sql" in sessions
    assert queries.pbi_sessions_sql(*pe.window()) in sessions        # verbatim, not a hand copy


def test_extracts_reuse_the_dashboard_query_text():
    W = pe.window()
    assert queries.pbi_session_listing_sql(*W).startswith(queries.category_sql(*W).split(",\nagg AS (")[0])
    assert queries.pbi_session_price_band_sql(*W).startswith(queries.price_band_sql(*W).split("\nSELECT price_band,")[0])
    assert queries.pbi_users_sql(*W).startswith(queries.cohort_sql(*W).split("\nSELECT f.cohort_week,")[0])


def _sessions():
    rows = []
    for dev, ch, vis, n, saw, bought in [("desktop", "organic", "new", 600, 150, 5), ("mobile", "referral", "returning", 400, 120, 8),
                                         ("desktop", "(not set)", "new", 300, 20, 0)]:
        for i in range(n):
            rows.append({"session_key": f"{dev}-{ch}-{i}", "device_category": dev, "channel_group": ch, "visitor_type": vis,
                         "saw_product": i < saw, "purchased": i < bought})
    return pd.DataFrame(rows)


def test_precompute_levels_tests_and_no_diagnosis_without_weak_pages():
    labels = pd.DataFrame({"item_category": ["Hats", "Google", "Apparel", "(not set)"],
                           "parent_node": ["Apparel", "Shop by Brand", "Home", None],
                           "n_source_labels": [2, 2, 2, 1], "source_labels": ["a", "b", "c", "d"],
                           "viewing_sessions": [900, 800, 700, 600], "median_price": [20.0, 15.0, 25.0, None]})
    landing = pd.DataFrame({"landing_page": ["/"], "sessions": [1300], "view_item": [290]})
    calls = []
    out = pe.precompute(_sessions(), labels, landing, run=lambda sql: calls.append(sql))
    lv = out["dim_listing"].set_index("item_category")
    assert lv.loc["Hats", "level"] == "product type" and lv.loc["Hats", "ranked"]
    assert lv.loc["Google", "level"] == "brand" and not lv.loc["Google", "ranked"]
    assert not lv.loc["(not set)", "ranked"]
    assert out["landing_diagnosis"].empty and not calls          # no weak page → no diagnosis query
    assert set(out["stats_tests"]["test"]) == {"device × purchase", "channel × saw a product (named channels)",
                                               "new vs returning × purchase"}


def test_cohort_flags_follow_the_dashboard_rules():
    # Public-sample window: 1 Nov 2020 (a Sunday) – 31 Jan 2021.
    d = pe.cohort_flags(pd.DataFrame({"cohort_week": ["2020-10-26", "2020-11-02", "2021-01-18", "2021-01-25"],
                                      "medium": ["x"] * 4, "users": [1] * 4, "wk1_users": [0] * 4}))
    assert list(d["full_cohort"]) == [False, True, True, True]          # the partial first week is not full
    assert list(d["week1_observed"]) == [True, True, True, False]       # the last cohort's Week 1 ends after 31 Jan


def test_price_band_dimension_comes_from_queries():
    out = pe.precompute(_sessions(), pd.DataFrame({"item_category": [], "parent_node": [], "n_source_labels": [],
                        "source_labels": [], "viewing_sessions": [], "median_price": []}),
                        pd.DataFrame({"landing_page": [], "sessions": [], "view_item": []}), run=lambda sql: None)
    assert list(out["dim_price_band"]["price_band"]) == [label for _, label in queries.PRICE_BANDS]

