#!/usr/bin/env python3
"""
powerbi_export.py
-----------------
Data for the Power BI version of the dashboard (roadmap E7). Every query comes
from queries.py — the dashboard's own SQL — so the two cannot drift apart.

Usage:
    python powerbi_export.py              # run the extracts under the cost cap → powerbi/data/*.csv
    python powerbi_export.py --dry-run    # bytes each extract would scan (free); runs nothing
    python powerbi_export.py --sql-only   # write the SQL to powerbi/sql/ for the BigQuery
                                          #   connector instead (no BigQuery call)

Project, dataset and window come from config.py (GA4_PROJECT_ID, GA4_DATASET,
GA4_DATE_START, GA4_DATE_END) and every query runs under GA4_MAX_BYTES_BILLED,
the same as generate_dashboard.py. The CSV route is the recommended one: Power
BI's BigQuery connector has no per-query cost cap.

Besides the row-level tables, the run writes the outputs of the rules DAX
cannot express well, computed with the dashboard's own functions (metrics.py,
stats_utils.py): listing-page levels, the landing-page diagnosis and the
significance tests.
"""

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

import config
import queries
from metrics import diagnose_landing_page, listing_levels, weak_landing_pages
from stats_utils import chi_square

HERE = Path(__file__).resolve().parent
MIN_LISTING_VIEWS = 500   # as MIN_CATEGORY_VIEWS in generate_dashboard.py

# (file name, query builder): the row-level tables of the model.
EXTRACTS = (
    ("fct_sessions", queries.pbi_sessions_sql),
    ("fct_session_listing", queries.pbi_session_listing_sql),
    ("fct_session_price_band", queries.pbi_session_price_band_sql),
    ("dim_users", queries.pbi_users_sql),
    ("fct_user_activity", queries.pbi_user_activity_sql),
    ("agg_cohort_channel", queries.cohort_channel_sql),
)
# Inputs to the pre-computed tables (aggregates, small).
INPUTS = (("listing_labels", queries.category_sql), ("landing_pages", queries.landing_pages_sql))


def window() -> tuple:
    return config.DATASET, config.DATE_START, config.DATE_END


def write_sql(out: Path) -> list[Path]:
    """The extract SQL as files, for pasting into the BigQuery connector."""
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, build in EXTRACTS:
        p = out / f"{name}.sql"
        p.write_text(f"-- {name}: generated by powerbi_export.py from queries.{build.__name__}\n"
                     f"-- window {config.DATE_START}–{config.DATE_END}; do not edit — regenerate.\n"
                     + build(*window()), encoding="utf-8")
        paths.append(p)
    return paths


def cohort_flags(cohorts: pd.DataFrame) -> pd.DataFrame:
    """agg_cohort_channel with the dashboard's eligibility rules as columns: a full
    cohort starts on or after the window start (Monday-anchored weeks make the
    first one partial otherwise), and its Week 1 is observed only if that whole
    week ends inside the window."""
    d = cohorts.copy()
    week = pd.to_datetime(d["cohort_week"]).dt.date
    d["full_cohort"] = week >= config.START
    d["week1_observed"] = [(w + pd.Timedelta(days=13).to_pytimedelta()) <= config.END for w in week]
    return d


def precompute(sessions: pd.DataFrame, labels: pd.DataFrame, landing: pd.DataFrame, run) -> dict:
    """The rule-based tables, from the extracts and the dashboard's own functions."""
    out = {}
    # Price bands in their natural order (queries.PRICE_BANDS — the dashboard's definition).
    out["dim_price_band"] = pd.DataFrame({"price_band": [label for _, label in queries.PRICE_BANDS],
                                          "band_order": range(1, len(queries.PRICE_BANDS) + 1)})
    # Listing-page levels (product type / brand / collection / parent) and which rows are ranked.
    lv = labels[["item_category", "parent_node", "n_source_labels", "source_labels",
                 "viewing_sessions", "median_price"]].copy()
    lv["level"] = listing_levels(lv["item_category"], lv["parent_node"])
    lv["ranked"] = ((lv["level"] == "product type") & (lv["item_category"] != "(not set)")
                    & (lv["viewing_sessions"] >= MIN_LISTING_VIEWS))
    out["dim_listing"] = lv.drop(columns=["viewing_sessions"])

    # Landing-page diagnosis for the weak landing pages.
    n = len(sessions)
    site_view = float(sessions["saw_product"].sum()) / n * 100 if n else 0.0
    weak = weak_landing_pages(landing, site_view, n)
    rows = []
    if len(weak):
        diag_rows = run(queries.landing_diagnosis_sql(*window(), pages=tuple(weak["landing_page"])))
        for pg in weak["landing_page"]:
            d = diagnose_landing_page(diag_rows[diag_rows["page_path"] == pg], site_view)
            g = d["gap"]
            rows.append({"landing_page": pg, "diagnosis": d["verdict"],
                         "landed_rate_pct": d["landed_rate"], "inside_rate_pct": d["inside_rate"],
                         "landed_untagged_pct": d["landed_untagged_pct"],
                         "gap_from": str(pd.Timestamp(g["start"]).date()) if g else None,
                         "gap_to": str((pd.Timestamp(g["end"]) + pd.Timedelta(days=6)).date()) if g else None})
    out["landing_diagnosis"] = pd.DataFrame(rows, columns=["landing_page", "diagnosis", "landed_rate_pct",
                                                           "inside_rate_pct", "landed_untagged_pct", "gap_from", "gap_to"])

    # Significance tests (DAX has no clean chi-square): the dashboard's definitions.
    tests = []
    def add(name, g, success):
        t = chi_square(g[success], g["n"])
        tests.append({"test": name, "chi2": t["chi2"], "dof": t["dof"], "p": t["p"], "cramers_v": t["cramers_v"]})
    dev = sessions.groupby("device_category").agg(n=("session_key", "size"), purchased=("purchased", "sum"))
    add("device × purchase", dev, "purchased")
    ch = sessions[~sessions["channel_group"].str.startswith(("other (", "(not set)"))]
    add("channel × saw a product (named channels)",
        ch.groupby("channel_group").agg(n=("session_key", "size"), saw=("saw_product", "sum")), "saw")
    vis = sessions[sessions["visitor_type"].isin(["new", "returning"])]
    add("new vs returning × purchase", vis.groupby("visitor_type").agg(n=("session_key", "size"), purchased=("purchased", "sum")), "purchased")
    out["stats_tests"] = pd.DataFrame(tests)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0].strip())
    ap.add_argument("--sql-only", action="store_true", help="write the extract SQL; no BigQuery call")
    ap.add_argument("--dry-run", action="store_true", help="estimate bytes per extract (free); runs nothing")
    ap.add_argument("--out", type=Path, default=None, help="output folder (default powerbi/data or powerbi/sql)")
    args = ap.parse_args(argv)

    if args.sql_only:
        paths = write_sql(args.out or HERE / "powerbi" / "sql")
        print(f"Wrote {len(paths)} SQL files to {paths[0].parent}")
        return 0

    client = config.make_client()
    print(f"Cost cap   |  {config.format_bytes(config.MAX_BYTES_BILLED)} billed per query (GA4_MAX_BYTES_BILLED)")
    builds = [b for _, b in EXTRACTS + INPUTS]
    if args.dry_run:
        total = 0
        for b in builds:
            n = config.estimate_bytes(client, b(*window()))
            total += n
            print(f"  {b.__name__:28s} {config.format_bytes(n):>10}")
        print(f"  {'total (+ the landing diagnosis)':28s} {config.format_bytes(total):>10}")
        return 0

    out = args.out or HERE / "powerbi" / "data"
    out.mkdir(parents=True, exist_ok=True)
    run = lambda sql: config.run_query(client, sql)
    frames = {}
    for name, build in EXTRACTS:
        print(f"Extracting {name}...")
        frames[name] = run(build(*window()))
    labels, landing = (run(b(*window())) for _, b in INPUTS)
    frames["agg_cohort_channel"] = cohort_flags(frames["agg_cohort_channel"])
    frames.update(precompute(frames["fct_sessions"], labels, landing, run))

    # Reconcile before writing: the session table must be the dashboard's funnel.
    funnel = run(queries.session_funnel_sql(*window())).iloc[0]
    s = frames["fct_sessions"]
    checks = {"sessions": len(s), "view_item": int(s["saw_product"].sum()), "add_to_cart": int(s["added_to_cart"].sum()),
              "begin_checkout": int(s["began_checkout"].sum()), "purchase": int(s["purchased"].sum())}
    bad = {k: (v, int(funnel[k])) for k, v in checks.items() if v != int(funnel[k])}
    if bad:
        print(f"ERROR: fct_sessions does not reconcile with the funnel: {bad}")
        return 1

    for name, df in frames.items():
        df.to_csv(out / f"{name}.csv", index=False)
    (out / "run_info.json").write_text(json.dumps({
        "dataset": config.DATASET, "window": [config.DATE_START, config.DATE_END],
        "generated": pd.Timestamp.now().strftime("%Y-%m-%d %H:%M"),
        "rows": {k: len(v) for k, v in frames.items()}, "funnel_check": checks}, indent=2), encoding="utf-8")
    print(f"\nWrote {len(frames)} tables to {out} — fct_sessions reconciles with the funnel ({checks['sessions']:,} sessions).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
